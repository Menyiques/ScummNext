def columns(rows):
    """7 filas de 5 -> 5 bytes, una columna por byte (bit 0 arriba)"""
    r = rows.split("|")
    assert len(r) == 7 and all(len(x) == 5 for x in r), rows
    return [sum(1 << y for y in range(7) if r[y][x] == "#") for x in range(5)]


def font_asm():
    order = [chr(c) for c in range(32, 127)] + [k for k in GLYPHS if ord(k) > 127]
    lines = ["; generado por tools/build.py desde tools/menufont.py", "GFONT:"]
    for ch in order:
        lines.append("        db " + ",".join("$%02X" % b for b in columns(GLYPHS[ch])))
    lines.append("GFEXT:                              ; (Latin-1, indice en GFONT)")
    for i, ch in enumerate(order):
        if ord(ch) > 127:
            lines.append("        db $%02X,%d" % (ord(ch), i))
    lines.append("        db 0")
    lines.append("GFQ     EQU %d                      ; '?'" % order.index("?"))
    return "\n".join(lines) + "\n"
